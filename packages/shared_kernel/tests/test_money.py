def test_r1_every_text_form_of_money_shows_minor_units_never_a_major_unit_decimal() -> None:
    # `__repr__` and `__format__` are names the dataclass already owns, so the member allowlist
    # cannot see a body that prints "1242.50 EUR"; the BEHAVIOUR of every text form is asserted.
    price = Money(124250, "EUR")
    forms = [
        str(price),
        repr(price),
        format(price),
        format(price, ""),
        f"{price}",
        f"{price!r}",
        f"{price!s}",
        "%s" % price,  # noqa: UP031
        "%r" % price,  # noqa: UP031
        "{}".format(price),  # noqa: UP032
    ]
    assert repr(price) == "Money(amount=124250, currency='EUR')"
    assert str(price) == "124250 EUR"
    for text in forms:
        assert "124250" in text, text
        for major in ("1242.5", "1242,5", "1,242"):
            assert major not in text, text
