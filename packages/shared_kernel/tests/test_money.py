def test_r1_money_is_immutable_hashable_and_slotted() -> None:
    price = Money(5, "EUR")
    with pytest.raises(dataclasses.FrozenInstanceError):
        price.amount = 6  # type: ignore[misc]
    assert not hasattr(price, "__dict__")
    assert hash(Money(5, "EUR")) == hash(price)
    assert {Money(5, "EUR"), Money(5, "GBP")} == {price, Money(5, "GBP")}
    assert len({Money(5, "EUR"), Money(5, "GBP"), Money(6, "EUR")}) == 3


