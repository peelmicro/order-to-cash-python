def test_r1_money_represents_1242_50_eur_as_124250_minor_units_no_decimal_representation() -> None:
    price = Money(124250, "EUR")
    assert price.amount == 124250
    assert type(price.amount) is int
    assert price.currency == "EUR"
    assert str(price) == "124250 EUR"
    assert [f.name for f in dataclasses.fields(Money)] == ["amount", "currency"]
    assert {f.name: f.type for f in dataclasses.fields(Money)} == {"amount": int, "currency": str}


