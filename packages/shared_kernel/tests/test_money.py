def test_r2_money_raises_a_domain_error_when_eur_and_gbp_are_added_subtracted_or_compared() -> None:
    eur, gbp = Money(100, "EUR"), Money(40, "GBP")
    for attempt in (
        lambda: eur.add(gbp),
        lambda: eur.subtract(gbp),
        lambda: eur.compare(gbp),
        lambda: eur + gbp,
        lambda: eur - gbp,
    ):
        with pytest.raises(CurrencyMismatchError) as raised:
            attempt()
        assert isinstance(raised.value, DomainError)
        assert raised.value.code == "money.cross_currency"
        assert (raised.value.left_currency, raised.value.right_currency) == ("EUR", "GBP")
    # No implicit conversion happened: both operands are untouched.
    assert (eur, gbp) == (Money(100, "EUR"), Money(40, "GBP"))


@pytest.mark.parametrize(
    "compare",
    [operator.lt, operator.le, operator.gt, operator.ge],
    ids=["lt", "le", "gt", "ge"],
)
def test_r2_each_ordering_operator_raises_across_currencies(
    compare: Callable[[Money, Money], bool],
) -> None:
    with pytest.raises(CurrencyMismatchError):
        compare(Money(1, "EUR"), Money(1, "GBP"))
    # ...and works inside one currency, so the raise is the currency check, not the operator.
    assert compare(Money(1, "EUR"), Money(2, "EUR")) in (True, False)


def test_r2_equality_across_currencies_is_false_not_an_error() -> None:
    # `==` asks "same value?"; ordering asks "which is larger?" and needs a rate (M2). #7 `equals`
    # (money.ts:109) and #8's record-struct equality both answer false.
    assert Money(100, "EUR") != Money(100, "GBP")
    assert not (Money(100, "EUR") == Money(100, "GBP"))  # noqa: SIM201
    assert Money(100, "EUR") == Money(100, "EUR")
    bare: Any = 100
    assert Money(100, "EUR") != bare  # never equal to a bare int


def test_r2_a_mismatch_at_either_operand_position_is_refused() -> None:
    with pytest.raises(CurrencyMismatchError):
        Money(1, "GBP") + Money(1, "EUR")
    with pytest.raises(CurrencyMismatchError):
        Money(1, "GBP") - Money(1, "EUR")


