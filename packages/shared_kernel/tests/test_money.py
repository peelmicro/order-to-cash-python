def test_m3_add_subtract_multiply_are_closed_over_the_same_currency() -> None:
    a, b = Money(1050, "EUR"), Money(250, "EUR")
    assert a.add(b) == Money(1300, "EUR") == a + b
    assert a.subtract(b) == Money(800, "EUR") == a - b
    assert a.multiply(Quantity(3)) == Money(3150, "EUR") == a * Quantity(3)
    assert Money(5, "JPY").multiply(Quantity(2)).currency == "JPY"


def test_m3_there_is_no_division_at_runtime() -> None:
    price: Any = Money(10, "EUR")
    for attempt in (
        lambda: price / 3,
        lambda: price // 3,
        lambda: price % 3,
        lambda: divmod(price, 3),
        lambda: float(price),
        lambda: int(price),
        lambda: round(price),
        lambda: 3 * price,
        lambda: 3 / price,
    ):
        with pytest.raises(TypeError):
            attempt()


@pytest.mark.parametrize("not_a_quantity", [3, True, 2.5, Money(1, "EUR"), "3", None])
def test_m3_multiplication_admits_a_quantity_and_nothing_else(not_a_quantity: Any) -> None:
    # #7 `multiply(quantity: Quantity)` (money.ts:88) and #8 `Multiply(Quantity)` (Money.cs:60)
    # take a Quantity only; a bare int is refused here at runtime too, not only by mypy.
    with pytest.raises(TypeError):
        Money(10, "EUR") * not_a_quantity
    with pytest.raises(AttributeError):
        Money(10, "EUR").multiply(not_a_quantity)


@pytest.mark.parametrize("operation", ["add", "subtract"])
def test_m3_arithmetic_beyond_the_bigint_column_is_refused_not_wrapped(operation: str) -> None:
    edge = Money(INT64_MAX, "EUR") if operation == "add" else Money(INT64_MIN, "EUR")
    with pytest.raises(InvalidMoneyAmountError):
        getattr(edge, operation)(Money(1, "EUR"))
    with pytest.raises(InvalidMoneyAmountError):
        Money(INT64_MAX, "EUR").multiply(Quantity(2))


def test_m4_negative_money_is_representable_and_a_subtraction_may_go_negative() -> None:
    discount = Money(-500, "EUR")
    assert discount.is_negative
    assert not discount.is_zero
    assert Money(100, "EUR").subtract(Money(300, "EUR")) == Money(-200, "EUR")
    assert Money.zero("EUR").is_zero
    assert not Money.zero("EUR").is_negative
    assert Money(-1, "EUR") < Money(0, "EUR") < Money(1, "EUR")


def test_compare_returns_minus_one_zero_one() -> None:
    assert Money(1, "EUR").compare(Money(2, "EUR")) == -1
    assert Money(2, "EUR").compare(Money(2, "EUR")) == 0
    assert Money(3, "EUR").compare(Money(2, "EUR")) == 1


def test_ordering_against_a_non_money_is_a_type_error() -> None:
    with pytest.raises(TypeError):
        Money(1, "EUR") < 5  # noqa: B015
    with pytest.raises(TypeError):
        Money(1, "EUR") + 5


